def save(path, header, rows):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "流水"
    ws.append(header)
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in rows:
        ws.append(list(r))
    for i, col in enumerate(ws.columns, 1):
        maxlen = max(len(str(c.value)) for c in col if c.value is not None)
        ws.column_dimensions[get_column_letter(i)].width = max(maxlen + 2, 12)
    wb.save(path)


